function detectLanguage() {
  const stored = localStorage.getItem('dilink-lang');
  if (stored && translations[stored]) return stored;
  const browser = (navigator.language || 'en').split('-')[0];
  const full = navigator.language || 'en';
  if (translations[full]) return full;
  const match = Object.keys(translations).find(k => k.startsWith(browser));
  return match || 'en';
}

const langToLocale = {
  en: 'en-US',
  'pt-BR': 'pt-BR',
  zh: 'zh-CN',
  ru: 'ru-RU',
  be: 'be-BY',
  fr: 'fr-FR',
  kk: 'kk-KZ',
  uk: 'uk-UA',
  uz: 'uz-UZ'
};

function getLangLocale() {
  return langToLocale[currentLang] || 'en-US';
}

let currentLang = detectLanguage();

// Called by version script when dates need re-rendering after language change
var onLanguageChange = null;

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('dilink-lang', lang);
  const t = translations[lang];
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) el.textContent = t[key];
  });
  const sel = document.getElementById('langSelect');
  if (sel) sel.value = lang;
  if (typeof onLanguageChange === 'function') onLanguageChange();
}

document.addEventListener('DOMContentLoaded', () => {
  applyLanguage(currentLang);
  const sel = document.getElementById('langSelect');
  if (sel) sel.addEventListener('change', e => applyLanguage(e.target.value));
});
